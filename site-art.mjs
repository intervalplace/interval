#!/usr/bin/env node
// THE WINDOW'S OWN ART, ON THE SITE'S PAPER.
//
// `site/items.js` was a hand-copied subset of window-web's drawing code: one
// hundred and fifteen lines of canvas calls, transcribed once and never
// checked again. Two pages loaded it, NOTHING on any page used it -- not one
// `data-item` anywhere in the site -- so the whole file was dead, and had it
// not been dead it would have gone stale, which is the worse of the two.
//
// The handbook already answered this: `sprite-svg.mjs` lifts the drawing code
// out of window-web.html on every run and replays it into SVG, so the
// pictures in the book are the pictures in the window by construction rather
// than by somebody remembering. This does the same for the site.
//
// The art is the one layer of this world that is not law (SPEC §0: "drawing
// it is not in the rules"), which is exactly why the window, the book and the
// site may all share it freely.
//
//   node site-art.mjs          writes site/art.js
//   node site-art.mjs --check  fails if site/art.js is not what it would write
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { spriteDataUri, beastDataUri } from './sprite-svg.mjs'
import E from './engine.js'

const HERE = fileURLToPath(new URL('.', import.meta.url))

// WHAT THE SITE SHOWS. Not all 132 items: a plate in a book is a selection,
// and this one is chosen to say what the island is rather than what it holds.
// One from each craft, the two things everybody starts with, and the three
// nobody will see for a year.
const PLATE = [
  ['iron-hatchet', 'the first tool anybody buys'],
  ['logs', 'and the first thing it makes'],
  ['raw-fish', 'pulled out of the Eastmere shallows'],
  ['cooked-fish', 'over a fire you lit yourself'],
  ['iron-ore', 'dug at Cragfoot'],
  ['iron', 'smelted at a furnace somebody else is stoking'],
  ['iron-sword', 'beaten at the one anvil on the island'],
  ['horn-bow', 'both hands, and nothing in the other'],
  ['ale', 'brewed at the Lantern, drunk anywhere'],
  ['sigil', 'the only mending a stranger can give you'],
  ['chart', 'drawn by somebody who walked it'],
  ['quick-sword', 'a year of somebody’s life'],
]
const BEASTS = [
  ['goblin', 'in the Wilds, in numbers'],
  ['wolf', 'where the woods are thickest'],
  ['skeleton-knight', 'past the Brandline'],
  ['dragon', 'once, and everybody will know'],
]

const unknown = PLATE.filter(([it]) => !E.ITEMS.has(it)).map(([it]) => it)
if (unknown.length) throw new Error('the plate names items this world has not got: ' + unknown.join(', '))
const noBeast = BEASTS.filter(([b]) => !E.MOB_STATS[b]).map(([b]) => b)
if (noBeast.length) throw new Error('the plate names creatures this world has not got: ' + noBeast.join(', '))

const items = {}, beasts = {}
for (const [it] of PLATE) items[it] = spriteDataUri(it)
for (const [b] of BEASTS) beasts[b] = beastDataUri(b, E.MOB_STATS[b].maxHealth ?? 5)

const out = `// GENERATED by site-art.mjs from window-web.html. Do not edit.
//
// Every picture below was drawn by the window's own code, replayed into SVG.
// Change a sprite in window-web.html and run \`node site-art.mjs\` again; the
// site and the window cannot drift, because there is only one drawing.
window.INTERVAL_ART = ${JSON.stringify({ items, beasts, plate: PLATE, beastPlate: BEASTS }, null, 1)}
// paint every <i data-item="..."> and <i data-beast="...">
document.addEventListener('DOMContentLoaded', () => {
  const A = window.INTERVAL_ART
  for (const el of document.querySelectorAll('[data-item],[data-beast]')) {
    const src = el.dataset.item ? A.items[el.dataset.item] : A.beasts[el.dataset.beast]
    if (!src) { el.remove(); continue }
    const img = document.createElement('img')
    img.src = src
    img.alt = (el.dataset.item ?? el.dataset.beast).replace(/-/g, ' ')
    img.className = el.className || 'itemicon'
    el.replaceWith(img)
  }
})
`
const path = HERE + 'site/art.js'
if (process.argv.includes('--check')) {
  let have = ''
  try { have = readFileSync(path, 'utf8') } catch {}
  if (have !== out) { console.error('site/art.js is stale: run `node site-art.mjs`'); process.exit(1) }
  console.log('site/art.js matches window-web.html')
} else {
  writeFileSync(path, out)
  console.log(`wrote site/art.js: ${PLATE.length} things and ${BEASTS.length} creatures,`
    + ` ${(out.length / 1024).toFixed(1)}K, all of it drawn by the window`)
}
